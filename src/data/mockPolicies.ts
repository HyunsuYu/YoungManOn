/** 오늘로부터 offset 일 뒤의 날짜를 YYYY-MM-DD 로 반환 (D-Day 데모용) */
function dateFromToday(offsetDays: number): string {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().slice(0, 10);
}

